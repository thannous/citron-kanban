import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../server.mjs';
import http from 'node:http';
test('HTTP contract: isolated modes, shared demo, errors, conflicts, private boundaries', async t => {
  const dir = await mkdtemp(join(tmpdir(),'citron-api-')); t.after(() => rm(dir,{recursive:true,force:true}));
  const server = await createApp({storePath:join(dir,'demo.json')});
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const get = path => fetch(base+path);
  const post = (path,body,headers={}) => fetch(base+path,{method:'POST',headers:{'Content-Type':'application/json',...headers},body:JSON.stringify(body)});
  const snapshot = await (await get('/api/board')).json(); assert.equal(snapshot.mode,'snapshot'); assert.equal(snapshot.linear.mode,'fixture');
  assert.equal(snapshot.cards.length,11); assert.equal(snapshot.cols.length,6); assert.equal(snapshot.capabilities.writeLinear,false);
  assert.deepEqual(snapshot.cols.map(([,name])=>name),['À faire','En cours','À trancher','Bloqué','À vérifier','Terminé']);
  assert.equal(snapshot.linearMapping.byName['In Review'],'verify');
  assert.deepEqual(snapshot.linearMapping.coordinationOnly,['decide','blocked']);
  assert.equal(snapshot.capabilities.agentExecution,false);
  assert.equal(snapshot.orchestration.configured,false);
  assert.deepEqual(snapshot.orchestration.runningAgents,[]);
  const op = {cardId:'drive',col:'doing',baseRevision:0,operationId:'api-operation-1'};
  assert.equal((await post('/api/move',op)).status,403);
  assert.equal((await post('/api/linear/refresh',{})).status,503);
  assert.equal((await post('/api/demo/failure?mode=demo',{})).status,200);
  assert.equal((await post('/api/move?mode=demo',op)).status,503);
  assert.equal((await post('/api/move?mode=demo',op)).status,200);
  const shared = await (await get('/api/board?mode=demo')).json(); assert.equal(shared.positions.drive.col,'doing');
  const retry = await (await post('/api/move?mode=demo',op)).json(); assert.equal(retry.duplicate,true); assert.equal(retry.revision,1);
  const conflict = await post('/api/move?mode=demo',{...op,col:'blocked',operationId:'api-operation-2'}); assert.equal(conflict.status,409);
  assert.equal((await conflict.json()).current.col,'doing');
  assert.equal((await (await get('/api/board')).json()).positions.drive.col,'todo');
  assert.equal((await get('/.private/seed.json')).status,404); assert.equal((await get('/data/linear-snapshot.json')).status,404);
  assert.equal((await post('/api/move?mode=demo',op,{Origin:'https://example.org'})).status,403);
  const denied = await new Promise((resolve,reject) => { const req=http.get(base+'/api/board',{headers:{Host:'attacker.example:4317'}},res=>{res.resume();resolve(res.statusCode);});req.on('error',reject); });
  assert.equal(denied,403);
  const html = await get('/'); assert.equal(html.status,200); assert.match(html.headers.get('Content-Security-Policy'),/frame-ancestors 'none'/);
  assert.equal((await get('/api/board?mode=unknown')).status,400);
  assert.equal((await post('/api/move?mode=demo',{...op,col:'invalid'})).status,400);
});
